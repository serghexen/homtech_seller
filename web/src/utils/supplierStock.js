// Объясняет решение по наличию отдельно от результата публикации в Яндексе.
export function supplierStockMessage(state) {
  if (!state?.observation || state.observation === 'disabled') return ''
  const labels = {
    zero: 'У поставщика остаток 0. Продажа через автовыдачу приостановлена.',
    item_error: 'Ошибка проверки номинала. Продажа через автовыдачу приостановлена.',
    unavailable: 'Номинал недоступен у поставщика. Продажа через автовыдачу приостановлена.',
    available: 'У поставщика есть товар. Публикуемый остаток ограничен заданным остатком и дневным лимитом.',
    common_error: 'Не удалось получить остатки поставщика.',
    stale: 'Опрос остатков поставщика задерживается.',
    unknown: 'Нет подтверждённых данных о наличии у поставщика.',
  }
  const message = labels[state.observation] || 'Состояние наличия требует проверки.'
  if (['common_error', 'stale', 'unknown'].includes(state.observation)) {
    return `${message} ${state.blocked ? 'Сохраняется ранее установленная блокировка.' : 'Автоматическое обнуление не выполняется.'}`
  }
  return message
}
